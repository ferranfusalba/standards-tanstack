export interface CountryCurrency {
  code: string;
  name: string;
  symbol?: string;
  type?: Currency["type"];
}

// Returns a map of country code → currencies for that country
export const getCurrenciesByCountry = createServerFn({
  method: "GET",
}).handler(async () => {
  const currencies = await getCurrencies();
  const map: Record<string, CountryCurrency[]> = {};

  for (const ccy of currencies) {
    if (!ccy.countries) continue;
    for (const code of ccy.countries) {
      if (!map[code]) map[code] = [];
      map[code].push({
        code: ccy.code,
        name: ccy.name,
        symbol: ccy.symbolIntl,
        type: ccy.type,
      });
    }
  }

  return map;
});
