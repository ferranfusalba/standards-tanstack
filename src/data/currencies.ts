export const getHistoricalCurrencies = createServerFn({
	method: "GET",
}).handler(async () => {
	return historicalCurrenciesBase.map((ccy) => ({
		...ccy,
		countryCode: countryNameToAlpha2[ccy.country.trim()],
	}));
});

export interface HistoricalCountryCurrency {
	code: string;
	name: string;
	withdrawalDate: string;
}

// Returns a map of country alpha-2 code → historical currencies for that country
export const getHistoricalCurrenciesByCountry = createServerFn({
	method: "GET",
}).handler(async () => {
	const currencies = await getHistoricalCurrencies();
	const map: Record<string, HistoricalCountryCurrency[]> = {};

	for (const ccy of currencies) {
		if (!ccy.countryCode) continue;
		if (!map[ccy.countryCode]) map[ccy.countryCode] = [];
		map[ccy.countryCode].push({
			code: ccy.code,
			name: ccy.name,
			withdrawalDate: ccy.withdrawalDate,
		});
	}

	return map;
});
