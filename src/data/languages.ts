export const getLanguages = createServerFn({
	method: "GET",
}).handler(async () => {
	const languages: Language[] = iso639_1Codes.map(({ code, name }) => {
		let nativeName: string | undefined;
		const bcp47Variants = bcp47VariantsByLanguage[code] || [];
		const cldrVariants = cldrVariantsByLanguage[code] || [];
		const intlVariants: string[] = [];

		try {
			// Get native name using the language's own code as locale
			const nativeNames = new Intl.DisplayNames([code], { type: "language" });
			nativeName = nativeNames.of(code);
		} catch (error) {
			// Some language codes might not be supported by Intl.DisplayNames
			nativeName = undefined;
		}

		// Test which CLDR variants are supported by Intl.DisplayNames
		if (cldrVariants.length > 0) {
			const displayNames = new Intl.DisplayNames(["en"], { type: "language" });
			for (const variant of cldrVariants) {
				try {
					// If DisplayNames can render it, it's supported
					const name = displayNames.of(variant);
					if (name && name !== variant) {
						intlVariants.push(variant);
					}
				} catch {
					// Variant not supported
				}
			}
		}

		return {
			code,
			name,
			nativeName,
			bcp47Variants: bcp47Variants.length > 0 ? bcp47Variants : undefined,
			cldrVariants: cldrVariants.length > 0 ? cldrVariants : undefined,
			intlVariants: intlVariants.length > 0 ? intlVariants : undefined,
		};
	});

	return languages;
});

/**
 * Every ISO 639-1 language's name in a single locale, as `{ code: name }`.
 * Server-computed (single CLDR source) so the "Localized Name" column matches
 * the rest of the app instead of relying on the browser's own CLDR data.
 */
export const getLanguageNamesByLocale = createServerFn({
	method: "GET",
})
	.inputValidator((data: { locale: string }) => data)
	.handler(async ({ data }): Promise<Record<string, string>> => {
		const displayNames = new Intl.DisplayNames([data.locale], {
			type: "language",
		});
		const names: Record<string, string> = {};
		for (const { code } of iso639_1Codes) {
			try {
				const localized = displayNames.of(code);
				if (localized && localized !== code) names[code] = localized;
			} catch {
				// Not renderable in this locale — skip.
			}
		}
		return names;
	});
